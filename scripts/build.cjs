// Deterministic, dependency-free packaging. app.js is committed so the app also
// runs directly from any static host without installing Node or running a build.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const files=['storage.js','i18n.js',...fs.readdirSync(path.join(root,'lang')).filter(f=>f.endsWith('.js')).sort().map(f=>'lang/'+f),
    'ui-locales.js','games1.js','games2.js','games3.js','games4.js','engine.js'];
const app='// Generated by npm run build. Edit the source files, not this bundle.\n'+files.map(f=>'\n// SOURCE: '+f+'\n'+fs.readFileSync(path.join(root,f),'utf8')).join('\n');
const hash=crypto.createHash('sha256').update(app);
for(const file of ['index.html','style.css','manifest.webmanifest','app-icon.svg','icon-192.png','icon-512.png'])hash.update(fs.readFileSync(path.join(root,file)));
const version=hash.digest('hex').slice(0,16);
const workerPath=path.join(root,'sw.js');
const worker=fs.readFileSync(workerPath,'utf8').replace(/const CACHE = '[^']+';/,"const CACHE = 'switch-games-"+version+"';");
const outputs=[['app.js',app],['sw.js',worker]];
if(process.argv.includes('--check')) {
    for(const [file,expected]of outputs)if(!fs.existsSync(path.join(root,file))||fs.readFileSync(path.join(root,file),'utf8')!==expected){console.error(file+' is stale: run npm run build');process.exit(1);}
    console.log('Bundle and offline cache version match source.');
} else {
    for(const [file,value]of outputs)fs.writeFileSync(path.join(root,file),value);
    console.log('Packaged '+files.length+' source files; cache '+version);
}
